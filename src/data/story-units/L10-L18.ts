import type { StorySegment, StoryUnit } from "../../domain/story-learning";

type Entry = readonly [string, string, string];
const make = (listId: StoryUnit["listId"], title: string, hook: string, texts: readonly string[], entries: readonly Entry[]): StoryUnit => {
  const segments = (text: string): StorySegment[] => text.split(/(\[\[L\d\d-[a-z]+\]\])/).filter(Boolean).map((part) => {
    const match = part.match(/^\[\[(.+)\]\]$/);
    return match ? { type: "word", wordId: match[1] } : { type: "text", text: part };
  });
  return { listId, title, hook, paragraphs: texts.map((text, index) => ({ id: `p${index + 1}`, segments: segments(text) })), usageNotes: Object.fromEntries(entries.map(([id, note]) => [id, note])), recallPrompts: entries.map(([wordId, , cue]) => ({ wordId, cue })) };
};

